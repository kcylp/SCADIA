def ch16(doc):
    h1(doc, '第 16 章  报表：把一段时间的数据交出去')
    para(doc, '报表解决的是“交材料”的问题：班后要交一张产量/能耗表，周会要交一张报警统计表。SCADIA 的报表是一份“定义”，按定义生成文档，可以预览、导出，也可以定时发到指定邮箱。')

    h2(doc, '16.1 报表定义有四个部分')
    table(doc, [
        ['部分', '作用', '关键设置'],
        ['基本信息', '报表叫什么、发给谁', '名称、接收者电子邮件'],
        ['调度', '什么时候自动生成', '禁用 / 每一天 / 每星期 / 每个月'],
        ['页面设置', '打印出来什么样', '页面大小、页面方向、上下左右边距'],
        ['内容', '报表里到底放什么', '文本 / 标签表 / 警报历史 / 图表，可混排'],
    ], widths=[3.2, 6.2, 7.1])

    h2(doc, '16.2 “标签表”是报表的主力')
    para(doc, '一张标签表的本质是：行是时间、列是变量、格子里是按某种统计方式算出来的值。所以只要配好三件事——选哪些标签、按什么时间范围、每格算什么——一张表就成立了。')
    table(doc, [
        ['设置项', '可选值', '说明'],
        ['表列标签', '从标签树里选，可多选', '一列一个变量；列标题可单独改'],
        ['数据范围', '无 / 年度 / 季度 / 班次 / 最后一天（0–24） / 上周（周一至周日） / 上个月', '决定“取哪一段”'],
        ['间隔（期间）', '5 / 10 / 15 / 30 分钟、1 小时、1 天', '决定“一段里切几行”'],
        ['功能类型', '最小 / 最大 / 平均 / 总和', '决定“每格怎么算”'],
        ['对齐 / 宽度', '左 / 中 / 右；列宽', '打印时的观感，建议数值右对齐'],
    ], widths=[3.6, 7.4, 5.5])
    note(doc, '“总和”适合电量、产量这类累加量；“平均”适合温度、压力；“最大/最小”适合找峰值。用错统计方式，数字看着正常但结论会错。')

    h2(doc, '16.3 报警历史与图表两项')
    bullets(doc, [
        '警报历史：可选优先级、要显示的列、以及报警过滤器。适合做“本月高优先级报警清单”；',
        '图表：给定名称、宽度、高度，把趋势线嵌进报表。适合在文字说明旁边放一张走势图。',
    ])

    h2(doc, '16.4 从零做一份班报表')
    bullets(doc, [
        '进入“报表”页面，点“添加”；',
        '名称填“甲班生产日报”，接收者填班组长邮箱（不需要自动发就留空）；',
        '调度先选“禁用”，等格式调好再打开；',
        '页面设置：A4、纵向、边距按打印预览调；',
        '内容区“添加文本”，写标题与班次说明；',
        '“添加标签表”，选 3–5 个关键标签，数据范围选“班次”，间隔 1 小时，功能类型选“平均”；',
        '“添加警报历史”，只保留高优先级，列选时间、文本、状态；',
        '预览，确认表头、单位、时间格式都对；',
        '把调度改为“每一天”，保存。',
    ], numbered=True)
    figure(doc, '06-reports', '图 16-1  报表页：左侧报表清单，右侧该报表的定义', 15.5)

    h2(doc, '16.5 本章验收清单')
    bullets(doc, [
        '预览里时间列、数值小数位、单位都正确；',
        '“总和”列与手工抽查的一段时间对得上；',
        '调度打开后，第二天能在邮箱里收到（需要先配好邮件服务器）；',
        '报表里不出现“配置项被当成生产数据”的表述。',
    ])


def ch17(doc):
    h1(doc, '第 17 章  配方：一次改一批参数')
    para(doc, '配方解决的是“同一台设备要按不同产品切换一组参数”的问题。例如同一台炉子做 A 产品要 180 ℃、B 产品要 210 ℃。把这些值存成“配方”，切换时一次性下发，比逐个改标签可靠。')

    h2(doc, '17.1 配方由什么组成')
    table(doc, [
        ['字段', '说明'],
        ['名称 / 描述', '配方叫法，建议带产品型号，例如“A 产品-标准”'],
        ['类型', '配方所属的类别，用于把同一类配方归在一起'],
        ['条目', '一行一个标签 + 一个目标值'],
        ['权限', '哪些角色可以看到、可以下发'],
    ], widths=[3.6, 12.9])

    h2(doc, '17.2 建一个配方的步骤')
    bullets(doc, [
        '进入“配方”页面，点“添加”；',
        '填名称、描述，选类型；',
        '在条目里逐行添加：选标签，填目标值，注意单位；',
        '保存后，用“查看/编辑”核对一遍条目数量与数值；',
        '在授权里指定可下发的角色（通常只给工程师及以上）。',
    ], numbered=True)
    figure(doc, '24-recipes', '图 17-1  配方页：名称、描述、条目数与操作菜单', 15.5)

    h2(doc, '17.3 下发的三条纪律')
    bullets(doc, [
        '先确认设备处于允许改参数的状态（停机或允许设定），再下发；',
        '下发后必须回读一遍关键标签，确认真的写进去了；',
        '配方不是“已执行”的证明：下发成功只代表写值成功，不代表工艺已达到目标。',
    ])
    note(doc, '本版本的配方页不承担“生产记录”职能。需要证明某批次用了哪套参数，要在报表或交接记录里留痕。')
