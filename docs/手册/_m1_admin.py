    note(doc, '多个角色是“相加”而不是“取最高”：同时给操作员(2)和工程师(4)，得到 6。管理员用 -1/255 表示全权限。不要给现场值班账号配管理员。')

    h2(doc, '18.2 建账号的标准动作')
    bullets(doc, [
        '进入“用户”页面，点“添加”；',
        '填用户名（建议拼音或工号）、全名（中文姓名）、初始密码；',
        '在“组”里勾选角色，按最小够用原则，例如值班只给查看器 + 操作员；',
        '保存，让本人首次登录后立即改密码；',
        '离职或换岗时，第一时间停用或删除，不要共用账号。',
    ], numbered=True)
    figure(doc, '10-users', '图 18-1  用户管理：账号、姓名与所属角色', 15.5)

    h2(doc, '18.3 角色管理')
    para(doc, '“角色”页面用来维护角色本身（名称、序号、描述）。内置八个位不建议删除；需要更细的区分时，用“授权”字段在具体对象上限定范围，而不是不断加角色。')
    figure(doc, '11-user-roles', '图 18-2  角色管理：角色清单与描述', 15.5)

    h2(doc, '18.4 授权字段出现在哪些地方')
