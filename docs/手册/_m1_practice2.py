    h2(doc, '29.1 选点：哪些量值得进报表')
    para(doc, '报表最怕“什么都想放”。一张 A4 放 6–8 列最舒服，超过 10 列就得横向打印，现场没人愿意看。选点按三条原则：')
    bullets(doc, [
        '能反映产量或能耗的（累计量、总量）；',
        '能反映工艺稳定性的（温度、压力、流量）；',
        '出事时一定会被追问的（关键设备电流、阀门状态）。',
    ])
    para(doc, '把选好的点写进下表，这张表就是报表的“设计图”，后面照着填即可。')
    table(doc, [
        ['列号', '标签', '单位', '统计方式', '小数位', '为什么放它'],
        ['1', '1#泵出口压力', 'MPa', '平均', '2', '判断泵是否正常出力'],
        ['2', '1#泵流量', 'm³/h', '平均', '1', '反映实际输送量'],
        ['3', '1#泵电流', 'A', '最大', '1', '过载最先体现在电流'],
        ['4', '累计电量', 'kWh', '总和', '1', '能耗核算'],
        ['5', '水池液位', 'm', '最小', '2', '夜班最低液位是关键'],
        ['6', '出水浊度', 'NTU', '最大', '1', '超标要追溯'],
    ], widths=[1.4, 4.2, 1.8, 2.4, 1.8, 4.4])

    h2(doc, '29.2 统计口径必须先说清楚')
    para(doc, '同一列数据，用“平均”还是“最大”，结论可能相反。所以报表定义里每一项都要能回答三个问题：取哪段时间、切成几段、每段怎么算。')
    table(doc, [
        ['设置项', '本次取值', '说明'],
        ['数据范围', '最后一天（0–24）', '即昨天 00:00 到 24:00，正好一个班次周期'],
        ['间隔（期间）', '1 小时', '24 行，正好一页'],
        ['功能类型', '按 29.1 表逐列设置', '累加量用总和，稳定性用平均/最大/最小'],
    ], widths=[3.6, 5.4, 7.5])
    note(doc, '“最后一天（0–24）”与“上个月”“上周”是互斥选项，选错会导致报表整体错位一天。调好后先预览再开调度。')

    h2(doc, '29.3 组装报表')
    bullets(doc, [
        '进入“报表”，点“添加”，名称写“运行班日报”；',
        '页面设置：A4、纵向；四边距各 1.5 cm；',
        '“添加文本”：第一行写站名与报表名，第二行写“统计周期：昨日 00:00–24:00”；',
        '“添加标签表”：按 29.1 的表逐列添加标签，设好单位、对齐（数值右对齐）；',
        '“添加警报历史”：优先级只留高，列选时间、文本、状态；',
        '预览：检查表头是否换行、数值是否带千分位、时间是否为 24 小时制；',
        '保存。',
    ], numbered=True)

    h2(doc, '29.4 打开自动发送前，先确认三件事')
    table(doc, [
        ['前置条件', '怎么确认', '不满足时'],
        ['邮件服务器已配置', '问管理员要 SMTP 地址、端口、发件账号', '调度能跑但发不出去'],
        ['接收者邮箱正确', '先用自己邮箱试一次', '改“接收者电子邮件”字段'],
        ['历史数据完整', '抽查昨天某个整点的曲线是否连续', '报表会出现空格子'],
    ], widths=[4.4, 7.4, 4.7])
    para(doc, '三项都满足后，把“报告调度”从“禁用”改为“每一天”，保存。第二天早上核对：收件时间、附件能否打开、数字与画面是否一致。')

    h2(doc, '29.5 手工对账：报表可信的唯一证明')
    para(doc, '不要因为“报表能生成”就认为它是对的。至少做一次手工对账：')
    bullets(doc, [
        '在曲线上选昨天 10:00–11:00，读出平均值；',
        '与报表对应格子比对，误差应在小数位允许范围内；',
        '累计量用“今日总量 − 昨日同一时刻总量”验算；',
        '报警条数与“报警页”同一天的筛选结果比对。',
    ])
    note(doc, '对账记录要留档（截图或签字），这是交付验收时最有力的一份证据。')
