"""第 14 章：报警配置与报警确认。

四档限值、Ack 模式、动作类型均取自 alarm.* 中文词条，为产品真实项。
"""

from _gen_lib import *


def build(doc):
    h1(doc, '第 14 章  报警：让系统主动喊人')
    para(doc, '画面要人盯着才看得到，报警不用。这一章讲清三件事：报警怎么定义、报警怎么确认、报警记录怎么查。')
    para(doc, '一个报警由三段组成：绑在哪个变量上、在什么数值区间算报警、报警之后系统做什么。三段任何一段没配好，报警都不会按你想的方式出现。')

    h2(doc, '14.1 一个报警的四档限值')
    para(doc, 'SCADIA 的每个报警可以同时配置四档，互不冲突。你可以只启用其中一档，也可以四档全用。')
    table(doc, [
        ['档位', '中文名', '典型用途', '举例（温度变量）'],
        ['高高低', '高高限', '危急，必须立即处理', '超过 95 ℃ 触发'],
        ['高低', '高限', '预警，需要关注', '超过 80 ℃ 触发'],
        ['低', '低限', '偏低预警', '低于 10 ℃ 触发'],
        ['信息', '信息级', '只提示、不告警', '设备切换为手动时提示一次'],
    ], widths=[2.2, 2.6, 5.6, 6.1])
    note(doc, '四档是“并列”关系，不是“升级”关系。如果你希望 80 ℃ 先提示、95 ℃ 再升级，需要两档都启用，并在“组”或“优先级”上区分，系统不会自动把高限升级成高高限。')

    h2(doc, '14.2 每一档要填的十个字段')
    para(doc, '打开报警属性，四档的字段完全一样。逐项含义如下，建议照表填，不要留空。')
    table(doc, [
        ['字段', '含义', '怎么填', '填错的后果'],
        ['已启用', '这一档是否生效', '不用的档位取消勾选', '留空会让人以为配了却没报'],
        ['文本', '报警时显示的文字', '写清“哪里、什么、怎么办”，不超过一行', '只写“报警”二字，值班员无法判断'],
        ['组', '归到哪个报警组', '按区域或设备归类，与画面筛选一致', '组混乱后历史查询筛不出来'],
        ['最小 / 最大', '触发区间的上下界', '高限填“限值→量程上限”，低限填“量程下限→限值”', '上下界填反，永远不触发'],
        ['时间延迟（秒）', '连续超限多久才真正报警', '波动大的量给 3–10 秒；开关量给 0', '给 0 会被瞬时毛刺反复触发'],
        ['检查间隔（秒）', '多久判断一次', '与设备轮询周期同量级，不要小于轮询周期', '小于轮询周期只是空转，判断不会更快'],
        ['Ack 模式', '怎么才算“已确认”', '见 14.4 三选一', '选错会出现“确认了又弹回来”'],
        ['颜色 / 背景色', '报警时的文字色与底色', '红底白字用于高高限；黄色用于预警', '全靠颜色区分，色弱人员看不懂'],
        ['授权', '哪些角色能看、能确认', '按 18 章的位掩码勾选角色', '授权过宽，普通账号能确认关键报警'],
    ], widths=[3.0, 4.2, 5.4, 4.4])

    h2(doc, '14.3 上下界到底怎么填')
    para(doc, '这是最容易填错的一处。记住一句话：区间填的是“触发范围”，不是“安全范围”。')
    bullets(doc, [
        '高高限 95：最小填 95，最大填量程上限（例如 150）。变量进入 95–150 就报警；',
        '高限 80：最小填 80，最大填 95。这样 80–95 报高限，95 以上报高高限，不会重复；',
        '低限 10：最小填量程下限（例如 0），最大填 10；',
        '信息级：把最小/最大填成同一个“触发值”，靠时间延迟避免抖动。',
    ])
    note(doc, '如果两档区间重叠（例如高限也填到 150），同一个数值会同时触发两条报警。重叠不是错误，但会让历史记录翻倍，排查时容易被误导。')

    h2(doc, '14.4 Ack 模式：三种确认语义')
    para(doc, 'Ack（确认）解决的是“这条报警谁来负责、什么时候算处理过”。三种模式含义不同，选错会出现“确认完又弹回来”。')
    table(doc, [
        ['模式', '中文名', '语义', '适用场景'],
        ['float', '浮动', '报警消失后自动结束，不需要人工确认', '只做记录、不需要追责的提示类报警'],
        ['ackactive', '允许主动报警的 Ack', '报警还在时可以先确认，确认后进入“活动-已确认”', '需要值班员签收的工艺报警（推荐）'],
        ['ackpassive', '只允许由被动报警器进行 Ack', '必须等报警条件消失后才允许确认', '不允许提前签收的安全类报警'],
    ], widths=[2.6, 5.0, 5.4, 4.0])

    h2(doc, '14.5 报警状态怎么看')
    table(doc, [
        ['状态', '中文', '含义', '值班员该做什么'],
        ['active', '活跃', '条件成立，尚未确认', '立即查看画面、判断真假、必要时到现场'],
        ['passive', '被动', '条件已消失，尚未确认', '补确认，并记录原因'],
        ['active-ack', '活动-已确认', '条件仍成立，但已有人签收', '继续跟踪，直到条件消失'],
    ], widths=[2.6, 3.0, 5.6, 5.6])

    h2(doc, '14.6 报警之后让系统做什么：六种动作')
    para(doc, '报警不只是弹一行字。每一档都可以挂动作，报警触发时自动执行。')
    table(doc, [
        ['动作', '效果', '关键参数', '注意'],
        ['显示弹幕', '在画面上叠加滚动提示条', '要显示的消息、类型', '不要用于高频报警，会刷屏'],
        ['设置视图', '自动切换到指定画面', '要显示的视图', '多人同时看同一台机器时会互相抢画面'],
        ['设置值', '把某个变量写成指定值', '目标变量、要设置的值', '会真实下发到设备，务必确认后再启用'],
        ['运行脚本', '执行一段脚本', '脚本名称', '脚本报错不影响报警本身，但动作会失败'],
        ['显示消息', '弹出提示消息', '要显示的消息、类型', '需要人工点掉，高频时会打断操作'],
        ['发送消息', '把消息推给外部通道', '消息内容', '外部通道未接通时只在日志里留痕'],
    ], widths=[2.8, 5.2, 4.6, 4.4])
    note(doc, '“设置值”是唯一会改变现场状态的动作。启用前请在调试环境验证一遍，并确认目标变量是可写类型；只读变量下发会被拒绝并记入日志。')

    h2(doc, '14.7 确认报警的标准动作')
    para(doc, '日常确认只有三步，顺序不要颠倒：')
    bullets(doc, [
        '先看：点开报警对应画面，确认现场状态与报警文字是否一致；',
        '再判：判断是真报警还是误报，误报要记下原因（传感器漂移、工况切换、检修中）；',
        '后确认：在报警页选中该条，点“ACK”，系统记录确认人与时间。',
    ], numbered=True)
    para(doc, '报警页上方有“ACK所有警报”按钮，只在交接班或大面积误报时使用。批量确认会一次性抹掉多条未处理报警的责任痕迹，事后追查会变难。')

    h2(doc, '14.8 报警记录怎么查')
    para(doc, '报警历史按时间倒序排列，列固定为：日期/时间、警报（变量名）、文本、优先级、状态。查询要点：')
    bullets(doc, [
        '先选时间范围，再选优先级；范围越大越慢；',
        '每页项目可调，默认 25 条；导出前先缩小范围；',
        '“场景事件确认后保留在历史中”——八场景事件确认后不会消失，仍可在历史里查到；',
        '历史记录不可编辑，这是审计要求，不要试图修改。',
    ])
    figure(doc, '23-alarms', '图 14-1  报警页：上方为当前报警，下方为历史记录，右上角为批量确认', 15.5)

    h2(doc, '14.9 本章验收清单')
    bullets(doc, [
        '随便挑一个模拟变量，把四档都填上，用调试值逐档触发，确认哪一档报、哪一档不报；',
        '确认“高限 80–95、高高限 95–150”不重叠；',
        '把时间延迟设成 5 秒，制造一次 1 秒的毛刺，确认不报警；',
        '按 14.7 的三步走一遍确认流程，确认状态从“活跃”变为“活动-已确认”；',
        '在历史里按时间范围查回刚才那条记录。',
    ])
