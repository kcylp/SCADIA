def ch10(doc):
    h1(doc, '第 10 章  动画连接：让画面动起来')
    para(doc, '组态软件的灵魂就是“动画连接”：把一个变量绑到元素上，规定“变量在什么范围内，元素表现成什么样”。本产品的动画在右侧属性面板的“动画”页签里配置。')

    h2(doc, '10.1 十七种动画动作')
    para(doc, '下表是本产品全部可用的动画动作。第一列是界面上的中文名，第二列说明它改变元素的什么表现。')
    table(doc, [
        ['动作', '作用'],
        ['隐藏', '条件成立时元素不可见'],
        ['显示', '条件成立时元素出现'],
        ['闪烁', '按设定频率明暗交替，用于提醒'],
        ['颜色', '按变量范围改变填充/文字颜色'],
        ['旋转', '按变量值旋转指定角度'],
        ['顺时针转动', '连续顺时针旋转（风机、泵）'],
        ['逆时针转弯', '连续逆时针旋转'],
        ['向上和向下', '在两点之间往返移动'],
        ['移动', '按变量值沿指定方向位移'],
        ['按标签移动', '用两个标签分别驱动 X、Y 位移'],
        ['停止', '条件成立时停下当前动画'],
        ['开始', '条件成立时启动动画'],
        ['暂停', '条件成立时暂停动画'],
        ['复位', '把元素恢复到初始状态'],
        ['更新图像', '条件成立时刷新图片内容'],
        ['加载图像', '按条件加载指定图片（状态图切换）'],
        ['监控', '把元素绑定到某路视频/监控源，作为画面内的监视窗'],
    ], widths=[3.4, 13.1])

    h2(doc, '10.2 一条动画由四段组成')
    para(doc, '不管选哪种动作，配置面板都是同一套逻辑，按顺序填四段就不会错：')
    bullets(doc, [
        '绑定：选哪个变量（必须先在变量词典里存在）；',
        '范围：变量的哪一段区间触发（最小值 / 最大值，可多段）；',
        '表现：触发后元素怎么变（颜色、角度、位移量、图片、频率）；',
        '条件（可选）：再叠加一个“使能”变量或权限，避免误动作。',
    ], numbered=True)
    para(doc, '举个例子：泵运行时叶轮转。绑定 pump1_run（布尔），范围“真”，表现选“顺时针转动”，速度填一个肉眼看着舒服的值。变量为假时自动停转，不需要再配一条“停止”。')

    h2(doc, '10.3 颜色动画的分段写法')
    para(doc, '颜色动画最容易配错，因为它是“区间叠加”的。正确做法是按从小到大的顺序，一段一段加：')
    table(doc, [
        ['区间', '颜色', '含义'],
        ['0 – 60', '绿', '正常'],
        ['60 – 80', '黄', '偏高'],
        ['80 – 9999', '红', '越限'],
    ], widths=[4.0, 3.0, 9.5])
    note(doc, '区间要首尾相接、不留缝、不重叠。留缝会出现“变回默认色”的闪跳，重叠则以先匹配到的那段为准，容易和直觉相反。')

    h2(doc, '10.4 位移与旋转的换算')
    para(doc, '位移和旋转都要求“变量值 → 像素/角度”的线性映射。填之前先在纸上算一遍：')
    bullets(doc, [
        '位移：满量程对应多少像素？例如液位 0–100% 对应 200 px，那么 1% 就是 2 px；',
        '旋转：满量程对应多少度？例如阀位 0–100% 对应 0–90°，那么角度 = 值 × 0.9；',
        '换算结果填在动画的“最大值/最小值”里，不要试图在脚本里每帧改位置。',
    ])
    note(doc, '如果发现元素往反方向动，把两个端点的值对调即可，不要去改画布坐标。')

    h2(doc, '10.5 动画之间的优先级')
    para(doc, '同一个元素上可以挂多条动画。实践中的稳定顺序是：先“显示/隐藏”，再“颜色”，最后“移动/旋转”。原因是：元素被隐藏时再做位移没有意义，而颜色和位置互不干扰。同一个属性（比如都在改颜色）挂两条动画会互相覆盖，只保留一条。')

    h2(doc, '10.6 本章验收清单')
    bullets(doc, [
        '每个动画都能说清“绑了哪个变量、哪段范围、变成什么样”；',
        '颜色区间无缝隙、无重叠；',
        '位移和旋转的换算在纸上验算过；',
        '同一属性上没有两条互相覆盖的动画；',
        '把变量强制改成边界值，画面表现符合预期（这是必做的验证动作）。',
    ], numbered=True)
