# -*- coding: utf-8 -*-
"""第 15 章：趋势曲线（图表控件）。

属性名取自 chart.* 中文词条：实时/历史/自定义、四条 Y 轴、插值方式、区域填充等。
"""

from _gen_lib import *


def build(doc):
    h1(doc, '第 15 章  趋势曲线：把数据画成线')
    para(doc, '组态软件里“趋势曲线”和“报表”是两件事：趋势看的是“变”，报表看的是“数”。本章讲怎么在画面上放一条能缩放、能回看历史的曲线。')

    h2(doc, '15.1 三种显示模式，先选对')
    para(doc, '图表控件的“显示模式”决定它取哪段时间的数据。选错模式，你会看到“曲线不动”或“没有数据”，但这通常不是故障。')
    table(doc, [
        ['显示模式', '取数范围', '典型用途'],
        ['实时', '从当前时刻往回推“最大分钟数”，并持续滚动刷新', '值班监视，看最近几分钟的波动'],
        ['历史', '按“日期范围”取固定时段，不随时间滚动', '事后分析、交接班复盘'],
        ['自定义', '由使用者在画面上自己选起止时间', '临时抽查某个时间段'],
    ], widths=[2.6, 8.4, 5.5])
    note(doc, '实时模式的“最大分钟数”就是它的记忆长度：设成 30，就只看最近 30 分钟。设得太小，会以为“数据丢了”。')

    h2(doc, '15.2 一条曲线由什么决定')
    para(doc, '图表里可以放多条线，每条线对应一个标签。线本身的属性如下。')
    table(doc, [
        ['属性', '作用', '怎么填'],
        ['名称 / 标签', '内部标识 / 图例上显示的文字', '标签建议用中文，例如“1#泵出口压力”'],
        ['来源（标签）', '这条线读哪个变量', '从标签树里选，不要手打'],
        ['Y 轴', '这条线用哪一根纵轴', '量纲不同的线要分轴，否则小信号会被压平'],
        ['颜色', '线的颜色', '同一画面最多 6 条线，超过就靠颜色也分不清'],
        ['插值', '两点之间怎么连', '线性（默认）/ 之后的步骤 / 之前的步骤 / 样条'],
        ['线宽 / 填充', '粗细 / 线下方是否着色', '趋势对比用细线，单值强调可加填充'],
        ['区域', '给某段区间加底色（最小 / 最大 / 描边 / 填充）', '用来标“正常区间”或“报警区间”'],
    ], widths=[3.4, 7.0, 6.1])
    para(doc, '插值方式会影响“看起来的样子”，但不会改数据：')
    bullets(doc, [
        '线性：两点直接连直线，最常用，也最不容易误读；',
        '之后的步骤：保持上一个值直到下一个采样点，适合开关量、状态量；',
        '之前的步骤：与上一条相反，适合“提前生效”的工艺量；',
        '样条：平滑过渡，好看但会“造出”原始数据里没有的拐点，报告里慎用。',
    ])

    h2(doc, '15.3 纵轴：为什么最多可以配四根')
    para(doc, '一张图上经常要同时看压力（MPa）、流量（m³/h）、温度（℃）。量纲差几十倍，挤在一根轴上小信号就成了一条直线。所以图表支持 Y1–Y4 四根纵轴，每根都能单独设标签、最小值、最大值。')
    table(doc, [
        ['设置项', '说明'],
        ['Y1–Y4 标签', '显示在轴旁边的文字'],
        ['Y1–Y4 最小 / 最大', '纵轴范围。留空则按数据自动缩放'],
        ['X 轴标签', '横轴说明，通常是时间'],
        ['小数位', '轴刻度保留几位小数'],
        ['网格', '是否显示网格线及网格颜色'],
    ], widths=[4.6, 11.9])
    note(doc, '纵轴最小值、最大值一旦手工固定，超范围的数据会被“切”在边界上，看起来像卡住。排查“曲线贴在顶上不动”时，先看这里。')

    h2(doc, '15.4 刷新、缩放与交互')
    table(doc, [
        ['属性', '默认', '说明'],
        ['刷新间隔（分钟）', '按现场设定', '多久去取一次数据。设得太小会频繁查库'],
        ['加载历史', '按需', '打开画面时是否顺带把历史读出来'],
        ['隐藏工具栏', '否', '全屏展示时常用'],
        ['触摸缩放 / 鼠标滚轮缩放', '按需', '现场触摸屏建议开；只用鼠标时可关'],
        ['鼠标滚轮滚动', '按需', '与缩放二选一，避免手势冲突'],
        ['主题', '明亮 / 黑暗 / 自定义', '与画面整体风格保持一致'],
    ], widths=[4.4, 3.4, 8.7])

    h2(doc, '15.5 做一张“泵站趋势”画面的完整步骤')
    bullets(doc, [
        '在变量词典里确认三个标签已存在且有历史数据：出口压力、流量、电流；',
        '打开组态编辑器，新建一个视图（或复用现有视图）；',
        '从控件栏拖入“图表”，在画布上拉出合适大小；',
        '在属性面板的“数据”页里新建图表，命名“泵站趋势”；',
        '依次“添加线”，每条线选一个标签，Y 轴分别设为 Y1、Y2、Y3；',
        '把三根轴的最小值、最大值按工艺量程填好，标签改成中文；',
        '显示模式选“实时”，最大分钟数设 30，刷新间隔设 1 分钟；',
        '保存视图，点“启动当前视图”预览，确认三条线都在动；',
        '切到“历史”模式，选昨天的日期范围，确认能回看。',
    ], numbered=True)
    note(doc, '第 9 步是验收关键：只能实时不能历史，说明这些标签没有开启历史存储（DAQ），要回到第 5.6 节补开，而不是怀疑图表坏了。')

    h2(doc, '15.6 本章验收清单')
    bullets(doc, [
        '三种显示模式都试过，知道各自取哪段数据；',
        '至少一条线用了第二根 Y 轴，量纲不同的信号没有互相压平；',
        '历史模式能查到昨天的曲线；',
        '关掉工具栏后画面仍能正常缩放（如果开了触摸/滚轮）。',
    ])
